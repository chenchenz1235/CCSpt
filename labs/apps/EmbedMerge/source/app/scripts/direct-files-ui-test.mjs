  assert.equal(await fs.readFile(files.test,'utf8'),'// 外部工具更新\r\n');checks.push('重启后恢复原文件任务和草稿，保留外部冲突状态');
  const dirs={ref:path.join(out,'project-ref'),test:path.join(out,'project-test')};for(const d of Object.values(dirs))await fs.mkdir(d);
  await fs.writeFile(path.join(dirs.ref,'same.c'),'int value=1;\n');await fs.writeFile(path.join(dirs.test,'same.c'),'int value=2;\n');
