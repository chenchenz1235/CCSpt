const executablePath=process.env.EMBEDMERGE_EXE||path.join(root,'release/EmbedMerge/EmbedMerge.exe');
const options={executablePath,args:[],cwd:root,env:{...process.env,ELECTRON_RUN_AS_NODE:undefined,EMBEDMERGE_DATA:path.join(out,'data')}};
