  assert.equal(await page.locator('#rightPath').textContent(),files.test);
  assert.match(await page.locator('#filename').textContent(),/reference.c ↔ target.h/);
  assert.equal(await page.locator('#autoMatlab').isDisabled(),true);
  checks.push('首页入口、左右文件选择器、不同名文件配对、直接保存状态及路径');
  await page.locator('[data-gutter-copy="0"][data-dir=right]').waitFor();
  await page.locator('[data-gutter-copy="0"][data-dir=right]').click();
  await page.waitForFunction(()=>document.querySelector('#dirtyLabel').textContent.includes('test'));
  assert.deepEqual(await fs.readFile(files.test),original);
  await page.locator('#saveCurrent').click();await page.waitForFunction(()=>document.querySelector('#saveCurrent').disabled);
  const firstSave=await fs.readFile(files.test);assert.ok(firstSave.toString().includes('2000'));assert.notDeepEqual(firstSave,original);
  const saved=await page.evaluate(()=>window.workbench.call('scan')),taskId=saved.task.id;
  const backupNames=await page.evaluate(()=>window.workbench.call('backups',{side:'test',rel:'reference.c'}));assert.equal(backupNames.length,1);
  assert.deepEqual(await fs.readFile(path.join(saved.task.backupRoot,'test','reference.c',backupNames[0])),original);
  checks.push('中间箭头仅改草稿、保存直接写回目标文件、磁盘旧字节自动备份');
  const input=page.locator('#editor textarea').nth(1);
  await input.press('Control+End');await page.keyboard.insertText('// 键盘保存\r\n');await input.press('Control+s');
  await page.waitForFunction(()=>document.querySelector('#saveCurrent').disabled);
  assert.match(await fs.readFile(files.test,'utf8'),/键盘保存/);checks.push('Ctrl+S 保存当前侧原文件');
  await page.screenshot({path:path.join(out,'01-direct-save.png')});
  await page.locator('#moreFile').click();await page.locator('#contextMenu button').filter({hasText:'其他编辑操作…'}).click();
  await page.locator('#contextMenu button').filter({hasText:'恢复 test 备份…'}).click();await page.locator('#backupDialog').waitFor({state:'visible'});
  const beforeRestore=await fs.readFile(files.test);await page.locator('#backupList button').last().click();
  assert.deepEqual(await fs.readFile(files.test),beforeRestore);await page.locator('#saveCurrent').click();await page.waitForFunction(()=>document.querySelector('#saveCurrent').disabled);
  assert.deepEqual(await fs.readFile(files.test),original);checks.push('备份恢复先到缓冲区，检查保存后恢复原文件');
  await input.press('Control+End');await page.keyboard.insertText('// 未保存草稿');
  await page.waitForFunction(()=>document.querySelector('#dirtyLabel').textContent.includes('test'));
  await fs.writeFile(files.test,'// 外部工具更新\r\n');await page.locator('#saveCurrent').click();
  await page.waitForFunction(()=>document.querySelector('#statusText').textContent.includes('冲突'));
  assert.equal(await fs.readFile(files.test,'utf8'),'// 外部工具更新\r\n');checks.push('外部更新冲突拒绝覆盖');
  await page.locator('#home').click();await page.locator('#saveChangesDialog button[value=draft]').click();await page.locator('#welcome').waitFor({state:'visible'});
